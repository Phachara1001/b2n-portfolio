                ไปที่โปรเจกต์ของคุณบน
                <a href="https://supabase.com" target="_blank" class="link-external">supabase.com
                  <ExternalLink :size="12" />
                </a>
                &gt; เข้าเมนู <strong>SQL Editor</strong> &gt; วางโค้ดนี้แล้วกด <strong>Run</strong>
              </p>
              <div class="code-box">
                <div class="code-box-header">
                  <span class="dots"><i></i><i></i><i></i></span>
                  <span>SQL Schema</span>
                  <button class="copy-btn" :class="{ done: copiedSql }" @click="copyText(sqlScript, 'sql')">
                    <Check v-if="copiedSql" :size="14" />
                    <Copy v-else :size="14" />
                    <span>{{ copiedSql ? 'คัดลอกแล้ว!' : 'คัดลอก SQL' }}</span>
                  </button>
                </div>
                <pre class="code-content"><code>{{ sqlScript }}</code></pre>
              </div>
            </div>
          </div>

