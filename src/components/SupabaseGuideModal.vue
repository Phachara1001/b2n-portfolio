            <div class="step-num">2</div>
            <div class="step-content">
              <div class="step-title">กำหนดค่า Environment Variables (.env)</div>
              <p class="step-desc">
                สร้างไฟล์ <code>.env</code> ไว้ที่โฟลเดอร์โปรเจกต์ (มีไฟล์ <code>.env.example</code> เป็นตัวอย่างแล้ว)
                และใส่ URL กับ Anon Key จาก Supabase:
              </p>
              <div class="code-box">
                <div class="code-box-header">
                  <span class="dots"><i></i><i></i><i></i></span>
                  <span>.env</span>
                  <button class="copy-btn" :class="{ done: copiedEnv }" @click="copyText(envTemplate, 'env')">
                    <Check v-if="copiedEnv" :size="14" />
                    <Copy v-else :size="14" />
                    <span>{{ copiedEnv ? 'คัดลอกแล้ว!' : 'คัดลอก' }}</span>
