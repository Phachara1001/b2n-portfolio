              LocalStorage ของบราวเซอร์) และเมื่อพร้อมต่อกับ Supabase ให้ทำตามขั้นตอนด้านล่างได้ทันที
            </div>
          </div>

          <div class="guide-step" style="--n: 1">
            <div class="step-num">1</div>
            <div class="step-content">
              <div class="step-title">สร้างตารางใน Supabase SQL Editor</div>
