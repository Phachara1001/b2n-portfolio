<script setup>
import { ref } from 'vue'
import { X, Copy, Check, Database, RotateCcw, ExternalLink } from 'lucide-vue-next'

const props = defineProps({
  isOpen: {
    type: Boolean,
    default: false
  },
  isConfigured: {
    type: Boolean,
    default: false
  }
})

const emit = defineEmits(['close', 'resetMock'])

const copiedSql = ref(false)
const copiedEnv = ref(false)

const sqlScript = `-- 1. สร้างตาราง projects สำหรับจัดเก็บผลงาน
create table projects (
  id bigint generated by default as identity primary key,
  title text not null,
  url text not null,
  description text,
  category text default 'Web App',
  image_url text,
  github_url text,
  tags text[],
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- 2. เปิดใช้งาน Row Level Security (RLS)
alter table projects enable row level security;

-- 3. นโยบายอนุญาตให้ทุกคนเข้าชมและเพิ่มผลงานได้
create policy "Allow public read-write" on projects
  for all using (true) with check (true);
`

const envTemplate = `VITE_SUPABASE_URL=https://your-project.supabase.co
VITE_SUPABASE_ANON_KEY=your-anon-public-key
`

function copyText(text, type) {
  navigator.clipboard.writeText(text)
  if (type === 'sql') {
    copiedSql.value = true
    setTimeout(() => { copiedSql.value = false }, 2000)
  } else if (type === 'env') {
    copiedEnv.value = true
    setTimeout(() => { copiedEnv.value = false }, 2000)
  }
}
</script>

